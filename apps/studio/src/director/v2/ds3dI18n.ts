export function createDs3dTr(locale: 'zh' | 'en' = 'en') {
  const table = locale === 'zh' ? ZH : EN;
  return (k: string, p?: Record<string, string | number>) => {
    let s = table[k] ?? EN[k];
    if (!s && k.startsWith('presets.')) s = k.slice('presets.'.length);
    if (!s) s = k;
    if (p) {
      for (const [key, val] of Object.entries(p)) s = s.replace(`{${key}}`, String(val));
    }
    return s;
  };
}
